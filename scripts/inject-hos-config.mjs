import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const url = (process.env.HOS_NARRATIVE_API_URL || '').trim();
const outPath = join(process.cwd(), 'work/hos/modules/hos-config.js');
const value = url ? JSON.stringify(url.replace(/\/$/, '')) : 'null';

const contents = `/** Generated by scripts/inject-hos-config.mjs — do not edit by hand. */
export const HOS_NARRATIVE_API_URL = ${value};
`;

writeFileSync(outPath, contents, 'utf8');
console.log(
  url
    ? `HOS narrative API URL injected (${url.length} chars).`
    : 'HOS narrative API URL not set; game uses local narration only.'
);
