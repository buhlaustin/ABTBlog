import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const defaultProd = 'https://austinbuhltech.com/api/hos/narrative';
const url = (process.env.HOS_NARRATIVE_API_URL || defaultProd).trim().replace(/\/$/, '');
const root = process.cwd();
const hosDir = join(root, 'work/hos');
const modulePath = join(hosDir, 'modules/hos-config.js');
const jsonPath = join(hosDir, 'narrative-api.json');
const indexPath = join(hosDir, 'index.html');

const value = url ? JSON.stringify(url) : 'null';

writeFileSync(
  modulePath,
  `/** Generated by scripts/inject-hos-config.mjs — do not edit by hand. */
export const HOS_NARRATIVE_API_URL = ${value};
`,
  'utf8'
);

writeFileSync(jsonPath, `${JSON.stringify(url ? { url } : { url: null }, null, 2)}\n`, 'utf8');

let indexHtml = readFileSync(indexPath, 'utf8');
const configScript = url
  ? `<script>window.__HOS_NARRATIVE_API_URL=${JSON.stringify(url)};</script>\n  `
  : '';

if (indexHtml.includes('window.__HOS_NARRATIVE_API_URL')) {
  indexHtml = indexHtml.replace(
    /<script>window\.__HOS_NARRATIVE_API_URL=[^<]*<\/script>\n\s*/,
    configScript
  );
} else {
  indexHtml = indexHtml.replace(
    '<script type="module" src="/play/hos/game.js"></script>',
    `${configScript}<script type="module" src="/play/hos/game.js"></script>`
  );
}
writeFileSync(indexPath, indexHtml, 'utf8');

console.log(
  url
    ? `HOS narrative API URL injected (${url.length} chars) into module, JSON, and index.html.`
    : 'HOS narrative API URL not set; game uses local narration only.'
);
