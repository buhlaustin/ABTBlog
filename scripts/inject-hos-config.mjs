import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const defaultProd = 'https://austinbuhltech.com/play/hos/narrate';
const rawUrl = (process.env.HOS_NARRATIVE_API_URL || defaultProd).trim().replace(/\/$/, '');
/** Same-origin proxy for HTML inject; modules also keep lambda URL for direct fallback after CORS fix. */
const url = rawUrl || defaultProd;
const clientModuleUrl =
  rawUrl && rawUrl.includes('lambda-url') ? rawUrl : url;
const root = process.cwd();
const hosDir = join(root, 'work/hos');
const eerDir = join(root, 'work/eer');
const modulePath = join(hosDir, 'modules/hos-config.js');
const jsonPath = join(hosDir, 'narrative-api.json');
const indexPath = join(hosDir, 'index.html');
const eerModulePath = join(eerDir, 'modules/eer-config.js');
const eerJsonPath = join(eerDir, 'narrative-api.json');
const eerIndexPath = join(eerDir, 'index.html');

const moduleValue = clientModuleUrl ? JSON.stringify(clientModuleUrl) : 'null';
const injectValue = url ? JSON.stringify(url) : 'null';

writeFileSync(
  modulePath,
  `/** Generated by scripts/inject-hos-config.mjs — do not edit by hand. */
export const HOS_NARRATIVE_API_URL = ${moduleValue};
`,
  'utf8'
);

writeFileSync(jsonPath, `${JSON.stringify(clientModuleUrl ? { url: clientModuleUrl } : { url: null }, null, 2)}\n`, 'utf8');

let indexHtml = readFileSync(indexPath, 'utf8');
const configScript = injectValue !== 'null'
  ? `<script>window.__HOS_NARRATIVE_API_URL=${injectValue};</script>\n  `
  : '';

if (indexHtml.includes('window.__HOS_NARRATIVE_API_URL')) {
  indexHtml = indexHtml.replace(
    /<script>window\.__HOS_NARRATIVE_API_URL=[^<]*<\/script>\n\s*/,
    configScript
  );
} else {
  indexHtml = indexHtml.replace(
    '<script type="module" src="/play/hos/game.js"></script>',
    `${configScript}<script type="module" src="/play/hos/game.js"></script>`
  );
}
writeFileSync(indexPath, indexHtml, 'utf8');

writeFileSync(
  eerModulePath,
  `/** Generated by scripts/inject-hos-config.mjs — do not edit by hand. */
export const EER_NARRATIVE_API_URL = ${moduleValue};
`,
  'utf8'
);
writeFileSync(eerJsonPath, `${JSON.stringify(clientModuleUrl ? { url: clientModuleUrl } : { url: null }, null, 2)}\n`, 'utf8');

let eerIndexHtml = readFileSync(eerIndexPath, 'utf8');
const eerConfigScript = injectValue !== 'null'
  ? `<script>window.__EER_NARRATIVE_API_URL=${injectValue};</script>\n  `
  : '';
if (eerIndexHtml.includes('window.__EER_NARRATIVE_API_URL')) {
  eerIndexHtml = eerIndexHtml.replace(
    /<script>window\.__EER_NARRATIVE_API_URL=[^<]*<\/script>\n\s*/,
    eerConfigScript
  );
} else {
  eerIndexHtml = eerIndexHtml.replace(
    '<script type="module" src="/play/eer/game.js"></script>',
    `${eerConfigScript}<script type="module" src="/play/eer/game.js"></script>`
  );
}
writeFileSync(eerIndexPath, eerIndexHtml, 'utf8');

console.log(
  url
    ? `Narrative API URL injected (${url.length} chars) into HOS + EER.`
    : 'Narrative API URL not set; games use local content only.'
);
